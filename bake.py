#!/usr/bin/env python3
"""Bake mono 16-bit sample data for SampleTone into samples.c / samples.h.

The Digitone has no sample engine and a machine mod cannot load a file at run
time, so the machine's sample bytes are compiled into the mod: this converts
and validates the input, writes a C table, and the mod is built against it.

  python3 bake.py a.wav [b.wav ...]        # bake your own sample(s)
  python3 bake.py --pack samples/          # bake every WAV/AIFF in a folder

The SAMP knob (SYN2 A) picks among the baked samples, so the pack mode is how
you carry a small sample set in one build.

Output (relative to the project root by default): samples.c, samples.h.
The mod requires core-dn1 4.0 for its 1.25 MB mod area, so the default cap is
1,200,000 bytes of sample data (about 12.5 s at 48 kHz or 25 s at 24 kHz mono
16-bit), which leaves headroom in the 1.25 MB area once the code is paid for.
Core-dn1 3.x's shared 128 KB area cannot hold a usable pack, so the mod
requires 4.0.

No sample is shipped with the mod: the table this writes is the only one the
build has, so a fresh clone is silent until you bake.

Input: PCM WAV or AIFF/AIFC (uncompressed), 8/16/24/32-bit integer, mono or
stereo; anything else is refused. The machine's voice is mono (one 32-sample
block a voice; the Digitone's pan, chorus, delay and reverb are all after it),
so a stereo source needs a choice: --downmix mid keeps both channels summed
(l+r)/2, left or right takes one and ignores the other. Rate conversion is
linear interpolation (deterministic, good enough for one-shot material;
pre-convert with a proper resampler if you care about aliasing). --trim keeps
the front of a sample and fades its tail, which is how a folder of drum hits
fits the mod's RAM. The output is little-endian int16.

Nothing is processed that does not need to be: a mono 16-bit source at the
bake rate is written frame for frame, and the report says so per file
(`verbatim`).
"""
import argparse
import math
import os
import struct
import sys
import wave

RATE = 48000                     # the Digitone render rate
DEFAULT_SAMPLE_RATE = 48000      # the Digitone render rate
DEFAULT_MAX_BYTES = 1200000      # inside core-dn1 4.0's 1.25 MB mod area

HEADER = """/* SPDX-License-Identifier: GPL-2.0-or-later */
/* Generated by %(tool)s - do not edit. */
#ifndef ST_SAMPLES_H
#define ST_SAMPLES_H

#include <stdint.h>

struct st_sample {
    const int16_t *pcm;     /* mono, signed 16-bit, little-endian in memory */
    uint32_t frames;        /* sample frames */
    uint32_t rate;          /* the rate the frames were recorded at */
    uint32_t kq16;          /* step per unit phase_inc, Q16 (rate/root/48 kHz) */
    uint8_t root;           /* MIDI note at which the sample plays at 1.0 */
    const char *name;       /* 5 characters for a SYN cell */
    const char *title;      /* up to 14 characters for the overlay */
};

extern const struct st_sample st_samples[];
extern const uint32_t st_sample_count;

#endif
"""


def inc_for_note(note):
    """The companion's dnm_inc[] formula (machines-dn1/tables.h)."""
    return int(440.0 * 2.0 ** ((note - 69) / 12.0) / RATE * (1 << 32) + 0.5)


def kq16_for(rate, root):
    """step_pos = (dnm_phase_inc(note) * kq16) >> 16, position in 32.32.

    At the root note this is rate/48000 frames an output frame, i.e. playback
    at the recorded pitch.
    """
    inc = inc_for_note(root)
    return (rate * (1 << 32) * (1 << 16)) // (RATE * inc)


def _decode(raw, width, big_endian, signed):
    if width == 1:
        if signed:
            return [b / 128.0 for b in raw]
        return [(b - 128) / 128.0 for b in raw]
    if width == 2:
        fmt = ">%dh" if big_endian else "<%dh"
        return [v / 32768.0 for v in struct.unpack(fmt % (len(raw) // 2), raw)]
    if width == 3:
        vals = []
        for i in range(0, len(raw) - 2, 3):
            b = raw[i:i + 3]
            if big_endian:                  # AIFF: the first byte is the MSB
                v = (b[0] << 16) | (b[1] << 8) | b[2]
            else:                           # WAV: the last byte is the MSB
                v = b[0] | (b[1] << 8) | (b[2] << 16)
            if v & 0x800000:
                v -= 1 << 24
            vals.append(v / 8388608.0)
        return vals
    if width == 4:
        fmt = ">%di" if big_endian else "<%di"
        return [v / 2147483648.0 for v in struct.unpack(fmt % (len(raw) // 4), raw)]
    raise ValueError("unsupported sample width %d" % width)


def mix_stereo(vals, mode):
    """One channel out of an interleaved pair: mid, left or right."""
    if mode == "left":
        return vals[0::2]
    if mode == "right":
        return vals[1::2]
    return [(vals[i] + vals[i + 1]) * 0.5 for i in range(0, len(vals) - 1, 2)]


def read_aiff(path, downmix="mid"):
    """PCM AIFF/AIFC (compression NONE or twos): mono/stereo, 8/16/24/32-bit."""
    raw = open(path, "rb").read()
    if raw[:4] != b"FORM" or raw[8:12] not in (b"AIFF", b"AIFC"):
        raise SystemExit("%s: not an AIFF file" % path)
    pos, ch, width, rate, nframes, data, little = 12, 0, 0, 0, 0, None, False
    while pos + 8 <= len(raw):
        cid = raw[pos:pos + 4]
        size = struct.unpack(">I", raw[pos + 4:pos + 8])[0]
        body = raw[pos + 8:pos + 8 + size]
        if cid == b"COMM" and len(body) >= 18:
            ch, nframes, width = struct.unpack(">hIh", body[:8])
            rate = _extended(body[8:18])
            if raw[8:12] == b"AIFC" and len(body) >= 22:
                comp = body[18:22]
                if comp == b"sowt":
                    little = True
                elif comp not in (b"NONE", b"twos"):
                    raise SystemExit("%s: compressed AIFC (%r); convert it to PCM"
                                     % (path, comp.decode("latin1")))
        elif cid == b"SSND" and len(body) >= 8:
            off = struct.unpack(">I", body[:4])[0]
            data = body[8 + off:]
        pos += 8 + size + (size & 1)
    if data is None or not ch or not width or not rate:
        raise SystemExit("%s: incomplete AIFF (no COMM or SSND)" % path)
    vals = _decode(data, width // 8, not little, True)   # AIFF PCM is signed at every width
    vals = vals[:nframes * ch]
    if ch == 2:
        vals = mix_stereo(vals, downmix)
    elif ch != 1:
        raise SystemExit("%s: %d channels; mono or stereo only" % (path, ch))
    return vals, int(round(rate)), ch, width // 8


def _extended(b):
    expon = struct.unpack(">H", b[:2])[0]
    if expon == 0:
        return 0.0
    sign = -1.0 if expon & 0x8000 else 1.0
    expon &= 0x7fff
    mant = int.from_bytes(b[2:10], "big")
    return sign * mant * 2.0 ** (expon - 16383 - 63)


def read_audio(path, downmix="mid"):
    """-> (values, source rate, source channels, source bytes a sample)."""
    if path.lower().endswith(".aif") or path.lower().endswith(".aiff") \
            or path.lower().endswith(".aifc"):
        return read_aiff(path, downmix)
    with wave.open(path, "rb") as w:
        ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        raw = w.readframes(n)
    if width not in (1, 2, 3, 4):
        raise SystemExit("%s: unsupported sample width %d" % (path, width))
    vals = _decode(raw, width, False, width > 1)
    if ch == 2:
        vals = mix_stereo(vals, downmix)
    elif ch != 1:
        raise SystemExit("%s: %d channels; mono or stereo only" % (path, ch))
    return vals, rate, ch, width


def resample(vals, src, dst):
    if src == dst or not vals:
        return list(vals)
    n = int(round(len(vals) * dst / src))
    out = []
    for i in range(n):
        x = i * src / dst
        i0 = int(x)
        frac = x - i0
        a = vals[i0] if i0 < len(vals) else 0.0
        b = vals[i0 + 1] if i0 + 1 < len(vals) else a
        out.append(a + (b - a) * frac)
    return out


def clamp16(v):
    if v > 32767:
        return 32767
    if v < -32768:
        return -32768
    return int(v)


def tool_name():
    """What the generated files say made them (bake.py, or tools/bake.py)."""
    return os.path.basename(sys.argv[0]) or "bake.py"


def unique_name(stem, used):
    """A 5-character name, disambiguated with a letter or digit suffix."""
    base = "".join(c for c in stem.upper() if c.isalnum())[:5] or "SMP"
    if base not in used:
        used.add(base)
        return base
    for ch in "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789":
        cand = base[:4] + ch if len(base) >= 5 else base + ch
        if cand not in used:
            used.add(cand)
            return cand
    raise SystemExit("too many samples share the name stem %r" % stem)


def bake(entries, out_c, out_h, max_bytes):
    total = sum(len(pcm) * 2 for pcm, _, _, _, _ in entries)
    if total > max_bytes:
        raise SystemExit(
            "refusing: %d bytes of sample data, cap is %d (core-dn1 4.0 gives "
            "the mod 1.25 MB). Lower --rate, shorten the sample, or raise "
            "--max-bytes only if you know the build has room." % (total, max_bytes))
    gen = "/* Generated by %s - do not edit. */" % tool_name()
    with open(out_h, "w") as f:
        f.write(HEADER % {"tool": tool_name()})
    lines = ["/* SPDX-License-Identifier: GPL-2.0-or-later */", gen,
             '#include "samples.h"', ""]
    rows = []
    for i, (pcm, rate, root, name, title) in enumerate(entries):
        lines.append("static const int16_t st_pcm_%d[%d] = {" % (i, len(pcm)))
        for j in range(0, len(pcm), 12):
            lines.append("    " + ", ".join(str(clamp16(v * 32768.0)) for v in pcm[j:j + 12]) + ",")
        lines.append("};")
        lines.append("")
        rows.append('    { st_pcm_%d, %du, %du, %du, %d, "%s", "%s" }, '
                    % (i, len(pcm), rate, kq16_for(rate, root), root, name[:5], title[:14]))
    lines.append("const struct st_sample st_samples[] = {")
    lines.extend(rows)
    lines.append("};")
    lines.append("const uint32_t st_sample_count = %du;" % len(entries))
    lines.append("")
    with open(out_c, "w") as f:
        f.write("\n".join(lines))
    return total


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("wav", nargs="*", help="mono/stereo WAV/AIFF file(s) to bake")
    ap.add_argument("--pack", metavar="DIR", help="bake every WAV/AIFF in DIR, sorted by name")
    ap.add_argument("--trim", type=float, default=0.0, metavar="SECONDS",
                    help="keep only the first SECONDS of each sample (0: all)")
    ap.add_argument("--fade", type=float, default=5.0, metavar="MS",
                    help="fade-out at the end of a trimmed sample (default 5 ms)")
    ap.add_argument("--out", default="samples.c", help="C file to write (default samples.c)")
    ap.add_argument("--header", default="samples.h", help="header to write (default samples.h)")
    ap.add_argument("--rate", type=int, default=DEFAULT_SAMPLE_RATE,
                    help="bake rate in Hz (default %d; 48000 keeps the source untouched)" % DEFAULT_SAMPLE_RATE)
    ap.add_argument("--root", type=int, default=60, help="MIDI note the sample plays at pitch (default 60, C4)")
    ap.add_argument("--downmix", choices=("mid", "left", "right"), default="mid",
                    help="stereo sources: mid sums both channels (l+r)/2 (default), "
                         "left or right takes one channel only")
    ap.add_argument("--name", default=None, help="5-character name for a single file (default: the file stem)")
    ap.add_argument("--max-bytes", type=int, default=DEFAULT_MAX_BYTES,
                    help="refuse more PCM than this (default %d)" % DEFAULT_MAX_BYTES)
    args = ap.parse_args(argv)

    if sum(bool(x) for x in (args.wav, args.pack)) != 1:
        ap.error("give WAV files, or --pack DIR (one of them)")
    if args.rate < 4000 or args.rate > 48000:
        ap.error("--rate must be 4000..48000")
    if not 0 <= args.root <= 127:
        ap.error("--root must be 0..127")

    entries = []
    if args.pack:
        if not os.path.isdir(args.pack):
            ap.error("--pack is not a directory: %s" % args.pack)
        paths = sorted(os.path.join(args.pack, f) for f in os.listdir(args.pack)
                       if f.lower().endswith((".wav", ".aif", ".aiff", ".aifc")))
        if not paths:
            ap.error("no WAV/AIFF files in %s" % args.pack)
        if len(paths) > 128:
            ap.error("a pack holds at most 128 samples (SAMP's 0..127)")
        args.wav = paths
    if args.name and len(args.wav) > 1:
        ap.error("--name applies to a single input; a pack names itself from the files")
    used = set()
    hows = []
    for path in args.wav:
        vals, rate, ch, width = read_audio(path, args.downmix)
        verbatim = ch == 1 and width == 2 and rate == args.rate
        vals = resample(vals, rate, args.rate)
        if args.trim > 0:
            keep = int(args.trim * args.rate)
            vals = vals[:keep]
            fade = min(len(vals), int(args.fade / 1000.0 * args.rate))
            for i in range(fade):
                vals[len(vals) - 1 - i] *= i / fade
        stem = os.path.splitext(os.path.basename(path))[0]
        name = args.name or unique_name(stem, used)
        how = []
        if ch == 2:
            how.append("stereo->" + args.downmix)
        if rate != args.rate:
            how.append("%gk->%gk" % (rate / 1000.0, args.rate / 1000.0))
        if width != 2:
            how.append("%db->16b" % (width * 8))
        if args.trim > 0:
            how.append("trimmed")
        hows.append("verbatim" if verbatim and not how else " ".join(how))
        entries.append((vals, args.rate, args.root, name, stem[:14]))

    # A sample must have at least two frames to interpolate.
    entries = [(v if len(v) > 1 else v * 2, r, root, n, t)
               for v, r, root, n, t in entries]

    total = bake(entries, args.out, args.header, args.max_bytes)
    for (pcm, rate, root, name, title), how in zip(entries, hows):
        print("%-6s %-14s %6d frames  %6.2f s  %7d bytes  %s"
              % (name, title, len(pcm), len(pcm) / rate, len(pcm) * 2, how))
    print("total %d bytes (cap %d); wrote %s and %s" % (total, args.max_bytes, args.out, args.header))
    if len(entries) > 1:
        print("\nSAMP (SYN2 A) picks among them: the engine reads "
              "index = value * %d / 128." % len(entries))
        for i, (pcm, rate, root, name, title) in enumerate(entries):
            lo = -(-128 * i // len(entries))
            hi = -(-128 * (i + 1) // len(entries)) - 1
            print("  SAMP %3d%s  %s" % (lo, "" if hi == lo else "-%d" % hi, name))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
